// Helper to interleave questions round-robin (EI -> SN -> TF -> JP -> EI -> SN ...)
function buildInterleavedQuestions(
  ei: Question[],
  sn: Question[],
  tf: Question[],
  jp: Question[],
  countPerAxis: number
): Question[] {
  const result: Question[] = [];
  for (let i = 0; i < countPerAxis; i++) {
    if (ei[i]) result.push(ei[i]);
    if (sn[i]) result.push(sn[i]);
    if (tf[i]) result.push(tf[i]);
    if (jp[i]) result.push(jp[i]);
  }
  return result;
}

